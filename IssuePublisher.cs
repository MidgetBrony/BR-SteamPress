using BR_MediaAPI;
using Newtonsoft.Json;
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace BR_SteamPress
{
    internal static class IssuePublisher
    {
        private const string BookMediaKey = "Rusty.BR-BookSystem";
        private const string MarkerName = ".br-steam-press-generated";

        internal static bool HasConfiguredLibrary()
        {
            try { return !string.IsNullOrWhiteSpace(MediaApi.GetLibraryFolder(BookMediaKey)); }
            catch { return false; }
        }

        internal static async Task<string> PublishTodayAsync(bool force)
        {
            string libraryRoot = MediaApi.GetLibraryFolder(BookMediaKey);
            if (string.IsNullOrWhiteSpace(libraryRoot))
                throw new InvalidOperationException("BR-BookSystem has no Book Folder Location configured.");

            DateTime issueDate = DateTime.Today;
            string issueId = $"steam_press_{issueDate:yyyy_MM_dd}";
            string folderName = $"Steam Press - {issueDate:yyyy-MM-dd}";
            string finalFolder = Path.Combine(libraryRoot, folderName);
            if (!force && File.Exists(Path.Combine(finalFolder, MarkerName)))
                return $"Today's Steam Press already exists in '{folderName}'.";

            var combinedStories = new List<NewsStory>();
            int sourceCount = 0;
            SteamGame[] games = Array.Empty<SteamGame>();
            if (SteamPressSettings.IncludeSteam)
            {
                IReadOnlyList<SteamGame> installed = SteamLibraryDiscovery.FindInstalledGames();
                IReadOnlyList<uint> selectedIds = SteamPressSettings.SelectedAppIds();
                if (selectedIds.Count > 0)
                {
                    var names = installed.ToDictionary(game => game.AppId, game => game.Name);
                    games = selectedIds.Select(id => new SteamGame
                    {
                        AppId = id,
                        Name = names.TryGetValue(id, out string name) ? name : $"Steam App {id}"
                    }).ToArray();
                }
                else
                {
                    games = installed.Take(SteamPressSettings.MaximumGames).ToArray();
                }

                if (games.Length > 0)
                {
                    using var steamClient = new SteamNewsClient();
                    combinedStories.AddRange(await steamClient.FetchAsync(games, SteamPressSettings.LookbackDays, SteamPressSettings.MaxStories).ConfigureAwait(false));
                    sourceCount += games.Length;
                }
            }

            IReadOnlyList<string> feedUrls = SteamPressSettings.FeedUrls();
            if (feedUrls.Count > 0)
            {
                using var rssClient = new RssFeedClient();
                combinedStories.AddRange(await rssClient.FetchAsync(feedUrls, SteamPressSettings.LookbackDays, SteamPressSettings.MaxStories).ConfigureAwait(false));
                sourceCount += feedUrls.Count;
            }

            if (sourceCount == 0)
                throw new InvalidOperationException("No Steam games or RSS/Atom feed URLs were found.");

            NewsStory[] stories = combinedStories
                .GroupBy(story => $"{story.GameName}|{story.Title}", StringComparer.OrdinalIgnoreCase)
                .Select(group => group.OrderByDescending(story => story.PublishedUnix).First())
                .GroupBy(story => story.GameName, StringComparer.OrdinalIgnoreCase)
                .SelectMany(group => group.OrderByDescending(story => story.PublishedUnix).Take(2))
                .OrderByDescending(story => story.PublishedUnix)
                .Take(SteamPressSettings.MaxStories)
                .ToArray();

            if (stories.Length == 0)
                throw new InvalidOperationException($"No recent stories were found in the last {SteamPressSettings.LookbackDays} days.");

            RenderedIssue rendered = NewspaperRenderer.Render(issueDate, stories);
            string temporaryFolder = Path.Combine(libraryRoot, $".{folderName}.tmp-{Guid.NewGuid():N}");
            Directory.CreateDirectory(libraryRoot);
            Directory.CreateDirectory(temporaryFolder);

            try
            {
                File.WriteAllText(Path.Combine(temporaryFolder, MarkerName), "Generated by BR-SteamPress.\n", new UTF8Encoding(false));
                File.WriteAllText(Path.Combine(temporaryFolder, "meta.json"), JsonConvert.SerializeObject(new
                {
                    Version = 2,
                    BookID = issueId,
                    Title = $"The Boxroom Press — {issueDate:d MMMM yyyy}",
                    Series = "The Boxroom Press",
                    Volume = issueDate.ToString("yyyy-MM-dd"),
                    Author = "Steam News",
                    Publisher = "BR-SteamPress",
                    ISBN = string.Empty,
                    Language = "en",
                    Type = "Magazine",
                    Summary = $"{stories.Length} recent stories from Steam and your RSS feeds, published {issueDate:d MMMM yyyy}."
                }, Formatting.Indented), new UTF8Encoding(false));
                File.WriteAllBytes(Path.Combine(temporaryFolder, "cover.jpg"), rendered.CoverJpeg);
                NewspaperRenderer.WriteCbz(Path.Combine(temporaryFolder, $"Steam Press {issueDate:yyyy-MM-dd}.cbz"), rendered.Pages);

                ReplaceGeneratedFolder(temporaryFolder, finalFolder);
                return $"Published {stories.Length} stories from {sourceCount} sources to '{folderName}'.";
            }
            finally
            {
                if (Directory.Exists(temporaryFolder)) Directory.Delete(temporaryFolder, true);
            }
        }

        private static void ReplaceGeneratedFolder(string temporaryFolder, string finalFolder)
        {
            if (!Directory.Exists(finalFolder))
            {
                Directory.Move(temporaryFolder, finalFolder);
                return;
            }

            if (!File.Exists(Path.Combine(finalFolder, MarkerName)))
                throw new IOException($"Refusing to replace '{finalFolder}' because it was not created by BR-SteamPress.");

            string backup = finalFolder + ".previous-" + Guid.NewGuid().ToString("N");
            Directory.Move(finalFolder, backup);
            try
            {
                Directory.Move(temporaryFolder, finalFolder);
                Directory.Delete(backup, true);
            }
            catch
            {
                if (!Directory.Exists(finalFolder) && Directory.Exists(backup)) Directory.Move(backup, finalFolder);
                throw;
            }
        }
    }
}
